// Dev-only element picker: point at any element, click, and a reference to it is copied to the clipboard,
// ready to paste into a chat with Claude ("fix this"). Framework-neutral; names the owning component and its
// source file where the dev build exposes it:
//   React 16–18 (fiber _debugSource) · React 19 (fiber _debugStack) · Next.js / Remix / Gatsby (React underneath)
//   Vue 3 / Nuxt (__vueParentComponent) · Svelte / SvelteKit (__svelte_meta)
//   Angular, Lit and other custom elements (tag → file map from gen-component-map.mjs; class name from customElements)
//   Server-rendered pages (Express/EJS, Django, Rails, Laravel, PHP …): optional data-source / data-component attributes
// Every page — any stack — also gets the DOM path, page URL, size and computed styles.
//
//   Toggle:  the "Pick" button (bottom-left) or Alt+Shift+X
//   Hover:   outlines the element and names it
//   ↑ / ↓:   pick the parent / go back down to the child
//   Click:   copy the reference (Shift+click: add it to the clipboard after the previous ones)
//   Esc:     stop picking (open panels, menus and popovers stay open)
//
// Works on overlays: pressing "Pick" or Alt+Shift+X is invisible to the app, so a panel that closes on an
// outside click, focus loss or Escape stays open while you pick inside it.
//
// Install from the app's dev entry only — see SKILL.md for each stack. Builds: element-picker.ts (source),
// element-picker.js (ES module), element-picker.iife.js (plain <script>, installs itself, reads window.ElementPickerOptions).

export interface PickerOptions {
  /** Angular, Lit or any custom-element app: host tag → source file + class name (generated by gen-component-map.mjs). */
  componentFiles?: Record<string, { file: string; name: string }>;
  /** Strip this prefix from source paths in the reference, e.g. the project root an absolute path starts with. */
  rootPrefix?: string;
  /** Tag prefixes of a design-system library to name as library components, e.g. ['mat-', 'sl-']. */
  libraryPrefixes?: string[];
}

const ATTR = 'data-element-picker';
const KEPT_ATTRS = ['aria-label', 'role', 'placeholder', 'title', 'type', 'name', 'href', 'data-testid'];

let opts: PickerOptions = {};
let active = false;
let hovered: HTMLElement | null = null;
let trail: HTMLElement[] = [];
let collected: string[] = [];
let box: HTMLDivElement;
let tag: HTMLDivElement;
let toggle: HTMLButtonElement;
let toast: HTMLDivElement;

export function installElementPicker(options: PickerOptions = {}): void {
  if (document.querySelector(`[${ATTR}="toggle"]`)) return;
  opts = options;
  injectStyles();

  box = el('div', 'box');
  tag = el('div', 'tag');
  toast = el('div', 'toast');
  toggle = el('button', 'toggle') as unknown as HTMLButtonElement;
  toggle.type = 'button';
  toggle.title = 'Pick an element to copy a reference for Claude (Alt+Shift+X)';
  toggle.innerHTML =
    '<svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"><circle cx="12" cy="12" r="7"/><path d="M12 2v4M12 18v4M2 12h4M18 12h4"/></svg><span>Pick</span>';
  document.body.append(box, tag, toast, toggle);

  window.addEventListener('keydown', onKey, true);
  document.addEventListener('mousemove', onMove, true);
  window.addEventListener('click', onClick, true);
  // Presses are caught on the way down (capture on window, before any app listener):
  //  • on the picker's own UI — always, so "Pick" never counts as an outside click and never moves focus;
  //  • anywhere while picking — so buttons, links and menus don't react to the pick.
  for (const type of ['mousedown', 'mouseup', 'pointerdown', 'pointerup', 'focusin', 'touchstart']) {
    window.addEventListener(
      type,
      (e) => {
        if (isOwn(e.target) || active) {
          if (type !== 'focusin') e.preventDefault();
          e.stopImmediatePropagation();
        }
      },
      { capture: true, passive: false },
    );
  }
}

function setActive(on: boolean): void {
  active = on;
  toggle.classList.toggle('on', on);
  document.documentElement.classList.toggle('element-picking', on);
  if (!on) {
    hovered = null;
    trail = [];
    box.style.display = tag.style.display = 'none';
  } else {
    flash('Picking: hover an element and click it. ↑ picks the parent. Esc stops.');
  }
}

function onKey(e: KeyboardEvent): void {
  if (e.altKey && e.shiftKey && e.code === 'KeyX') {
    e.preventDefault();
    e.stopImmediatePropagation();
    setActive(!active);
    return;
  }
  if (!active) return;
  if (e.key === 'Escape') {
    e.preventDefault();
    e.stopImmediatePropagation();
    setActive(false);
  } else if (e.key === 'ArrowUp' && hovered?.parentElement && hovered.parentElement !== document.body) {
    e.preventDefault();
    trail.push(hovered);
    show(hovered.parentElement);
  } else if (e.key === 'ArrowDown' && trail.length) {
    e.preventDefault();
    show(trail.pop()!);
  }
}

function onMove(e: MouseEvent): void {
  if (!active) return;
  const target = document.elementFromPoint(e.clientX, e.clientY) as HTMLElement | null;
  if (!target || isOwn(target) || target === hovered || trail.includes(target)) return;
  trail = [];
  show(target);
}

function onClick(e: MouseEvent): void {
  if (isOwn(e.target)) {
    e.preventDefault();
    e.stopImmediatePropagation();
    if ((e.target as Element).closest(`[${ATTR}="toggle"]`)) setActive(!active);
    return;
  }
  if (!active) return;
  e.preventDefault();
  e.stopImmediatePropagation();
  if (!hovered) return;
  const ref = describe(hovered);
  collected = e.shiftKey ? [...collected, ref] : [ref];
  copy(collected.join('\n\n'));
  const n = collected.length;
  flash(n > 1 ? `Copied ${n} elements. Paste them into the chat.` : 'Copied. Paste it into the chat.');
  if (!e.shiftKey) setActive(false);
}

function show(target: HTMLElement): void {
  hovered = target;
  const r = target.getBoundingClientRect();
  Object.assign(box.style, { display: 'block', top: `${r.top}px`, left: `${r.left}px`, width: `${r.width}px`, height: `${r.height}px` });
  const comp = owners(target).find((o) => !o.library);
  tag.textContent = `${comp ? comp.name + ' › ' : ''}${short(target)}  ${Math.round(r.width)}×${Math.round(r.height)}`;
  tag.style.display = 'block';
  tag.style.top = `${r.top < 28 ? r.bottom + 4 : r.top - 24}px`;
  tag.style.left = `${Math.max(4, Math.min(r.left, innerWidth - tag.offsetWidth - 4))}px`;
}

// ── Which component owns an element ──

interface Owner { name: string; file?: string; tag?: string; library?: boolean }

/** Component owners from the element outwards, using whatever the framework's dev build exposes. */
function owners(node: HTMLElement): Owner[] {
  const out: Owner[] = [];
  const seen = new Set<string>();
  const push = (o: Owner) => {
    if (o.file) o.file = cleanPath(o.file);
    const key = `${o.name}|${o.file ?? ''}`;
    if (!seen.has(key)) {
      seen.add(key);
      out.push(o);
    }
  };
  for (let n: HTMLElement | null = node; n && n !== document.body; n = n.parentElement) {
    const t = n.tagName.toLowerCase();
    const any = n as any;

    // Server-rendered templates or hand-tagged markup: <div data-source="views/orders.ejs" data-component="OrderCard">
    const src = n.getAttribute('data-source') ?? n.getAttribute('data-source-file');
    const comp = n.getAttribute('data-component');
    if (src || comp) push({ name: comp ?? src!.split('/').pop()!, file: src ?? undefined });

    // Angular / Lit / custom elements: generated tag → file map, else the registered class name.
    const known = opts.componentFiles?.[t];
    if (known) push({ name: known.name, file: known.file, tag: t });
    else if (opts.libraryPrefixes?.some((p) => t.startsWith(p))) push({ name: t, tag: t, library: true });
    else if (t.includes('-') && typeof customElements !== 'undefined' && customElements.get(t)) {
      push({ name: customElements.get(t)!.name || t, tag: t });
    }

    // Vue 3 / Nuxt (dev): component instance on the element.
    const vue = any.__vueParentComponent;
    if (vue?.type) push({ name: vue.type.__name || vue.type.name || 'Anonymous', file: vue.type.__file });

    // Svelte / SvelteKit (dev): source location on the element.
    const svelte = any.__svelte_meta;
    if (svelte?.loc?.file) push({ name: svelte.loc.file.split('/').pop()!.replace(/\.svelte$/, ''), file: `${svelte.loc.file}:${svelte.loc.line}` });

    // React / Next.js / Remix / Gatsby (dev): walk the fiber up to the components that rendered this element.
    const fiberKey = Object.keys(n).find((k) => k.startsWith('__reactFiber$') || k.startsWith('__reactInternalInstance$'));
    if (fiberKey && n === node) {
      for (let f = any[fiberKey]; f; f = f.return) {
        if (typeof f.type !== 'function' && typeof f.type?.render !== 'function') continue;
        const type = typeof f.type === 'function' ? f.type : f.type.render;
        const name = f.type.displayName || type.displayName || type.name || 'Anonymous';
        // React ≤18: _debugSource. React 19: _debugStack (an Error captured where the element was created).
        const file = f._debugSource ? `${f._debugSource.fileName}:${f._debugSource.lineNumber}` : fromStack(f._debugStack?.stack);
        push({ name, file });
      }
    }
  }
  return out;
}

/** First stack frame that is app code (not React, a bundler chunk or node_modules), as "path:line". */
function fromStack(stack?: string): string | undefined {
  if (!stack) return undefined;
  for (const line of stack.split('\n').slice(1)) {
    const m = /((?:https?|file|webpack-internal|rsc):\/\/\S+?):(\d+):\d+\)?$/.exec(line.trim());
    if (!m) continue;
    const url = m[1];
    if (/node_modules|react-dom|react-jsx|jsx-dev-runtime|\/chunks?\/|\.vite\/deps|next\/dist|_next\/static/.test(url)) continue;
    return `${url}:${m[2]}`;
  }
  return undefined;
}

/** "http://localhost:5173/src/App.tsx?t=17" → "src/App.tsx"; also webpack-internal, file:// and the root prefix. */
function cleanPath(file: string): string {
  let f = file.replace(/^webpack-internal:\/\/\/(\([^)]*\)\/)?/, '').replace(/^rsc:\/\/[^/]+\/[^/]+\//, '');
  f = f.replace(/^file:\/\//, '').replace(/^https?:\/\/[^/]+\//, '').replace(/\?[^:]*(?=(:\d+)?$)/, '').replace(/^\.\//, '');
  if (opts.rootPrefix && f.startsWith(opts.rootPrefix)) f = f.slice(opts.rootPrefix.length).replace(/^\//, '');
  return decodeURIComponent(f);
}

function describe(node: HTMLElement): string {
  const r = node.getBoundingClientRect();
  const cs = getComputedStyle(node);
  const own = owners(node);
  const app = own.filter((o) => !o.library);
  const lib = own.find((o) => o.library);
  const lines = ['[UI element]', `Element: ${open(node)}${textOf(node)}`];
  if (lib && own[0] === lib) lines.push(`Library component: ${lib.tag}`);
  if (app[0]) lines.push(`Component: ${app[0].name}${app[0].tag ? ` <${app[0].tag}>` : ''}${app[0].file ? ` — ${app[0].file}` : ''}`);
  if (app.length > 1) lines.push(`Inside: ${app.slice(1, 4).map((o) => o.name + (o.file ? ` (${o.file})` : '')).join(' › ')}`);
  lines.push(`Path: ${path(node)}`);
  lines.push(`Page: ${location.pathname}${location.hash}`);
  lines.push(`Size: ${Math.round(r.width)}×${Math.round(r.height)} at x=${Math.round(r.left)}, y=${Math.round(r.top)} (window ${innerWidth}×${innerHeight})`);
  lines.push(
    `Styles: font ${cs.fontSize}/${cs.lineHeight} ${cs.fontWeight} · color ${cs.color} · background ${cs.backgroundColor} · ` +
      `padding ${cs.padding} · margin ${cs.margin} · radius ${cs.borderRadius} · display ${cs.display}`,
  );
  return lines.join('\n');
}

function open(node: HTMLElement): string {
  const cls = typeof node.className === 'string' ? node.className.trim().replace(/\s+/g, ' ') : '';
  const attrs = [cls ? `class="${cls}"` : '', ...KEPT_ATTRS.filter((a) => node.hasAttribute(a)).map((a) => `${a}="${node.getAttribute(a)}"`)].filter(Boolean);
  return `<${node.tagName.toLowerCase()}${attrs.length ? ' ' + attrs.join(' ') : ''}>`;
}

function textOf(node: HTMLElement): string {
  const text = (node.innerText || node.getAttribute('aria-label') || '').trim().replace(/\s+/g, ' ');
  return text ? ` "${text.length > 80 ? text.slice(0, 80) + '…' : text}"` : '';
}

function short(node: HTMLElement): string {
  const cls = typeof node.className === 'string' ? node.className.trim().split(/\s+/).filter((c) => c && !c.startsWith('ng-')).slice(0, 3) : [];
  return node.tagName.toLowerCase() + cls.map((c) => '.' + c).join('');
}

function path(node: HTMLElement): string {
  const parts: string[] = [];
  for (let n: HTMLElement | null = node; n && n !== document.body && parts.length < 8; n = n.parentElement) {
    parts.unshift(short(n));
    if (n !== node && opts.componentFiles?.[n.tagName.toLowerCase()]) break;
  }
  return parts.join(' > ');
}

// ── Plumbing ──

function copy(text: string): void {
  navigator.clipboard?.writeText(text).catch(() => fallbackCopy(text)) ?? fallbackCopy(text);
}

function fallbackCopy(text: string): void {
  const ta = document.createElement('textarea');
  ta.value = text;
  ta.setAttribute(ATTR, 'clip');
  ta.style.cssText = 'position:fixed;opacity:0;';
  document.body.append(ta);
  ta.select();
  document.execCommand('copy');
  ta.remove();
}

let toastTimer: ReturnType<typeof setTimeout>;
function flash(msg: string): void {
  toast.textContent = msg;
  toast.classList.add('on');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove('on'), 2600);
}

function isOwn(t: EventTarget | null): boolean {
  return t instanceof Element && !!t.closest(`[${ATTR}]`);
}

function el(name: string, role: string): HTMLDivElement {
  const n = document.createElement(name) as HTMLDivElement;
  n.setAttribute(ATTR, role);
  return n;
}

