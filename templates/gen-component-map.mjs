// Angular, Lit, Stencil and plain web components: scans src/ for element tags and writes a tag → file map
// for the dev element picker (frameworks whose DOM already carries source info don't need it).
// Usage: node scripts/gen-component-map.mjs [outFile]   (default: src/app/dev/component-files.ts; a .js outFile gets no types)
// Runs automatically before `npm start` / `npm run build` (see package.json "prestart" / "prebuild").
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = join(root, 'src');
const out = process.argv[2] ? join(root, process.argv[2]) : join(src, 'app/dev/component-files.ts');
const map = {};

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { if (name !== 'node_modules' && !name.startsWith('.')) walk(p); }
    else if (/\.(ts|js|mjs)$/.test(p) && !/\.(spec|test|stories)\.\w+$/.test(p) && p !== out) {
      const text = readFileSync(p, 'utf8');
      const file = relative(root, p);
      // Angular: @Component({ selector: 'app-x' }) … export class X
      for (const m of text.matchAll(/selector:\s*['"]([^'"]+)['"][\s\S]*?export class (\w+)/g)) {
        for (const sel of m[1].split(',').map((s) => s.trim())) {
          if (/^[a-z][\w-]*$/.test(sel)) map[sel] = { file, name: m[2] };
        }
      }
      // Lit / Stencil: @customElement('my-x') class X  ·  @Component({ tag: 'my-x' }) class X
      for (const m of text.matchAll(/(?:@customElement\(\s*|tag:\s*)['"]([a-z][\w-]*-[\w-]*)['"][\s\S]*?class (\w+)/g)) map[m[1]] ??= { file, name: m[2] };
      // Plain web components: customElements.define('my-x', X)
      for (const m of text.matchAll(/customElements\.define\(\s*['"]([a-z][\w-]*-[\w-]*)['"]\s*,\s*(\w+)/g)) map[m[1]] ??= { file, name: m[2] };
    }
  }
}

walk(src);
const body = Object.keys(map).sort().map((k) => `  '${k}': { file: '${map[k].file}', name: '${map[k].name}' },`).join('\n');
const type = out.endsWith('.ts') ? ': Record<string, { file: string; name: string }>' : '';
writeFileSync(out, `// Generated by scripts/gen-component-map.mjs — do not edit.\nexport const COMPONENT_FILES${type} = {\n${body}\n};\n`);
console.log(`component map: ${Object.keys(map).length} components → ${relative(root, out)}`);
